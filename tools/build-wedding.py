#!/usr/bin/env python3
"""Builds js/wedding.js — the wedding page for Dri — from the SAME code the
app uses (js/app.js), so both always look and behave alike. Only the pieces
the wedding screen needs are copied; nothing else of the app goes in.
Run after changing the wedding code in app.js (tools/assets.py runs it)."""
import re, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, 'js/app.js'), encoding='utf8').read().split('\n')

def line_of(start):
    for i, l in enumerate(src):
        if l.startswith(start): return i
    sys.exit('build-wedding: not found: ' + start)

def block(start):
    """a top-level statement starting with `start`, up to its closing line at column 0"""
    i = line_of(start); l = src[i]
    if l.count('{') == l.count('}') and l.count('(') == l.count(')') and not l.rstrip().endswith(('{', '(', '[', ',')):
        return src[i]   # a whole statement on one line
    for j in range(i + 1, len(src)):
        if src[j] in ('}', '};') or src[j].startswith('};') or src[j].startswith('})'):
            return '\n'.join(src[i:j + 1])
    sys.exit('build-wedding: no end for ' + start)

def region(a, b):
    """from the line starting with a, through the line starting with b"""
    i, j = line_of(a), line_of(b)
    return '\n'.join(src[i:j + 1])

parts = [
    block('const MONTHS_HE'),
    block('const genId'),
    block('const fmtMoney'),
    block('function toast(msg)'),
    block('function _escape(s)'),
    block('function dailyDateStr(d)'),
    block('let _spF = null;'),
    block('const _spISO'),
    region('window.spFlowOpen = function', 'window.spFlowFull = function'),
    block('window.spentSheet = function'),
    block('const FZ = {'),
    block('const _RM_KINDS = {'),
    block('function _rmIcon(k)'),
    block('window.phoneTypeSheet = function'),
    block('const _ctClean'),
    block('const _phPretty'),
    block('window.contactPick = async function'),
    block('function _waPhone(p)'),
]
# the wedding module itself: from its header comment through wedExp
i = next(k for k, l in enumerate(src) if l.startswith('// ── v625: החתונה'))
j = line_of('window.wedExp = function')
for k in range(j + 1, len(src)):
    if src[k] == '};': j = k; break
parts.append('\n'.join(src[i:j + 1]))
out = '// GENERATED by tools/build-wedding.py from js/app.js — do not edit by hand.\n' + '\n\n'.join(parts) + '\n'
open(os.path.join(ROOT, 'js/wedding.js'), 'w', encoding='utf8').write(out)
print('wedding.js ok (%d lines)' % out.count('\n'))
